#!/usr/bin/env python3
"""
Writes the launcher icon as Android vector drawables.

The mark: a six-six in ivory, tipped as if just laid, in front of the eight-petalled
rosette from the glazed brick of the Ishtar gate, on lapis. Everything inside the 66dp
safe circle of the 108dp adaptive canvas, so no launcher mask can clip it.

    python3 tools/icon/make_icon.py
"""
import math
from pathlib import Path

RES = Path(__file__).resolve().parents[2] / "app/src/main/res/drawable"
C = 54.0  # centre of the 108dp canvas


def f(x):
    return f"{x:.2f}".rstrip("0").rstrip(".")


def circle(cx, cy, r):
    return f"M{f(cx - r)},{f(cy)} a{f(r)},{f(r)} 0 1,0 {f(2 * r)},0 a{f(r)},{f(r)} 0 1,0 {f(-2 * r)},0 z"


def rounded(x, y, w, h, r):
    return (
        f"M{f(x + r)},{f(y)} h{f(w - 2 * r)} a{f(r)},{f(r)} 0 0,1 {f(r)},{f(r)} "
        f"v{f(h - 2 * r)} a{f(r)},{f(r)} 0 0,1 {f(-r)},{f(r)} h{f(-(w - 2 * r))} "
        f"a{f(r)},{f(r)} 0 0,1 {f(-r)},{f(-r)} v{f(-(h - 2 * r))} a{f(r)},{f(r)} 0 0,1 {f(r)},{f(-r)} z"
    )


def ellipse(cx, cy, rx, ry):
    return f"M{f(cx - rx)},{f(cy)} a{f(rx)},{f(ry)} 0 1,0 {f(2 * rx)},0 a{f(rx)},{f(ry)} 0 1,0 {f(-2 * rx)},0 z"


def linear(x1, y1, x2, y2, stops):
    items = "".join(f'\n                    <item android:offset="{o}" android:color="{c}" />' for o, c in stops)
    return f"""
            <aapt:attr name="android:fillColor">
                <gradient android:type="linear" android:startX="{f(x1)}" android:startY="{f(y1)}"
                    android:endX="{f(x2)}" android:endY="{f(y2)}">{items}
                </gradient>
            </aapt:attr>"""


def radial(cx, cy, r, stops):
    items = "".join(f'\n                    <item android:offset="{o}" android:color="{c}" />' for o, c in stops)
    return f"""
            <aapt:attr name="android:fillColor">
                <gradient android:type="radial" android:centerX="{f(cx)}" android:centerY="{f(cy)}"
                    android:gradientRadius="{f(r)}">{items}
                </gradient>
            </aapt:attr>"""


def vector(body):
    return f"""<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by tools/icon/make_icon.py; edit that, not this. -->
<vector xmlns:android="http://schemas.android.com/apk/res/android"
    xmlns:aapt="http://schemas.android.com/aapt"
    android:width="108dp"
    android:height="108dp"
    android:viewportWidth="108"
    android:viewportHeight="108">
{body}
</vector>
"""


# -- geometry -------------------------------------------------------------------------

ROSETTE_R = 30.0          # petal tips; just inside the visible circle, a halo round the tile
PETAL_W = ROSETTE_R * 0.40
TILE_W, TILE_H = 21.0, 40.5
TILE_TILT = -14.0         # degrees
TILE_CX, TILE_CY = C + 1.0, C + 1.5
PIP_R = 1.95
SIX = "#FFD9A21B"


def pip_centres():
    x0, y0 = TILE_CX - TILE_W / 2, TILE_CY - TILE_H / 2
    half = TILE_H / 2
    cols = [x0 + TILE_W * 0.29, x0 + TILE_W * 0.71]
    pips = []
    for top in (y0, y0 + half):
        for row in (0.22, 0.5, 0.78):
            for x in cols:
                pips.append((x, top + half * row))
    return pips


def foreground():
    x0, y0 = TILE_CX - TILE_W / 2, TILE_CY - TILE_H / 2
    gold = linear(C, C - ROSETTE_R, C, C, [(0, "#FFF0CC72"), (0.45, "#FFD19E3B"), (1, "#FF8A5E17")])
    # Petals, gold, lit from above.
    petal_xml = []
    for i in range(8):
        petal_xml.append(f"""    <group android:rotation="{i * 45 + 22.5}" android:pivotX="{f(C)}" android:pivotY="{f(C)}">
        <path android:pathData="{ellipse(C, C - ROSETTE_R / 2, PETAL_W / 2, ROSETTE_R / 2)}"
            android:strokeColor="#FF7A5216" android:strokeWidth="0.7">{gold}
        </path>
        <!-- the glaze catching the light -->
        <path android:pathData="{ellipse(C - 1.6, C - ROSETTE_R * 0.62, 1.3, ROSETTE_R * 0.26)}"
            android:fillColor="#73FFF6DC" />
    </group>""")
    tile = []
    tile.append(f"""    <group android:rotation="{TILE_TILT}" android:pivotX="{f(TILE_CX)}" android:pivotY="{f(TILE_CY)}">
        <!-- shadow on the rosette -->
        <path android:pathData="{rounded(x0 + 1.6, y0 + 2.4, TILE_W, TILE_H, 4.2)}" android:fillColor="#59160B02" />
        <!-- the bone, its edge, then its face -->
        <path android:pathData="{rounded(x0, y0, TILE_W, TILE_H, 4.2)}" android:fillColor="#FFB9AA8F" />
        <path android:pathData="{rounded(x0 + 0.7, y0 + 0.6, TILE_W - 1.4, TILE_H - 1.6, 3.6)}">{linear(x0, y0, x0 + TILE_W, y0 + TILE_H, [(0, "#FFFFFDF7"), (0.6, "#FFF6EFE2"), (1, "#FFE4D9C4")])}
        </path>
        <!-- the bar across the middle, with its brass pin -->
        <path android:pathData="M{f(x0 + 3.4)},{f(TILE_CY - 0.45)} h{f(TILE_W - 6.8)} v0.9 h{f(-(TILE_W - 6.8))} z" android:fillColor="#FFB3A487" />
        <path android:pathData="{circle(TILE_CX, TILE_CY, 1.3)}" android:fillColor="#FFC9A24E" />""")
    for (px, py) in pip_centres():
        tile.append(f"""        <path android:pathData="{circle(px, py + 0.35, PIP_R)}" android:fillColor="#40553F12" />
        <path android:pathData="{circle(px, py, PIP_R)}">{radial(px - 0.7, py - 0.8, PIP_R * 1.6, [(0, "#FFF7D46A"), (0.55, SIX), (1, "#FFA97A0C")])}
        </path>""")
    tile.append("    </group>")
    return vector("\n".join(petal_xml) + "\n" + f"""    <path android:pathData="{circle(C, C, 4.6)}" android:fillColor="#FFA67C2E" />\n""" + "\n".join(tile))


def background():
    # Lapis, lit from the upper middle, with the coursing of glazed brick just visible.
    body = [f"""    <path android:pathData="M0,0 h108 v108 h-108 z">{radial(54, 44, 78, [(0, "#FF2C5E9C"), (0.5, "#FF1B3F70"), (1, "#FF0B1E3A")])}
    </path>"""]
    lines = []
    y = 7.0
    row = 0
    while y < 108:
        lines.append(f"M0,{f(y)} h108 v0.5 h-108 z")
        x = 4.0 if row % 2 else 11.0
        while x < 108:
            lines.append(f"M{f(x)},{f(y - 9 + 0.5)} h0.5 v8.5 h-0.5 z")
            x += 14.0
        y += 9.0
        row += 1
    body.append(f'    <path android:pathData="{" ".join(lines)}" android:fillColor="#14000000" />')
    # A gilt ring at the edge of what launchers show.
    ring = circle(C, C, 35.2) + " " + circle(C, C, 34.4)
    body.append(f'    <path android:pathData="{ring}" android:fillType="evenOdd" android:fillColor="#59D9B166" />')
    return vector("\n".join(body))


def monochrome():
    """Themed icons tint by opacity alone: petals half-strength, the tile solid with its pips cut out."""
    parts = []
    for i in range(8):
        parts.append(f"""    <group android:rotation="{i * 45 + 22.5}" android:pivotX="{f(C)}" android:pivotY="{f(C)}">
        <path android:pathData="{ellipse(C, C - ROSETTE_R / 2, PETAL_W / 2, ROSETTE_R / 2)}" android:fillColor="#FFFFFFFF" android:fillAlpha="0.55" />
    </group>""")
    x0, y0 = TILE_CX - TILE_W / 2, TILE_CY - TILE_H / 2
    holes = " ".join(circle(px, py, PIP_R) for px, py in pip_centres())
    bar = f"M{f(x0 + 3.4)},{f(TILE_CY - 0.6)} h{f(TILE_W - 6.8)} v1.2 h{f(-(TILE_W - 6.8))} z"
    parts.append(f"""    <group android:rotation="{TILE_TILT}" android:pivotX="{f(TILE_CX)}" android:pivotY="{f(TILE_CY)}">
        <path android:pathData="{rounded(x0, y0, TILE_W, TILE_H, 4.2)} {holes} {bar}" android:fillType="evenOdd" android:fillColor="#FFFFFFFF" />
    </group>""")
    return vector("\n".join(parts))


if __name__ == "__main__":
    RES.mkdir(parents=True, exist_ok=True)
    (RES / "ic_launcher_foreground.xml").write_text(foreground())
    (RES / "ic_launcher_background.xml").write_text(background())
    (RES / "ic_launcher_monochrome.xml").write_text(monochrome())
    print("wrote", RES)
